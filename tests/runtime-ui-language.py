os.chdir('/home/frappe/frappe-bench/sites')
frappe.init(site='accounting', sites_path='/home/frappe/frappe-bench/sites')
frappe.connect()
frappe.set_user('Administrator')
try:
    catalog = get_all_translations('nb')
    missing = []
    checked = 0
    for doctype in DOCTYPES:
        meta = frappe.get_meta(doctype)
        for field in meta.fields:
            texts = [field.label, field.description]
            if field.fieldtype == 'Select':
                texts.extend((field.options or '').split('\n'))
            for source in texts:
                if not source or source in TECHNICAL:
                    continue
                checked += 1
                if not (catalog.get(source + ':' + doctype) or catalog.get(source)):
                    missing.append((doctype, field.fieldname, source))
    assert not missing, missing
    assert frappe._('VAT', lang='nb') == 'MVA'
    assert frappe._('Value Added Tax', lang='nb') == 'Merverdiavgift'
    assert frappe._('Rate', lang='nb', context='Item Price') == 'Enhetspris'
    # Native currency rates still retain their distinct meaning.
    assert frappe._('Exchange Rate', lang='nb') != 'Enhetspris'
    print(f'PASS native NB metadata catalog: {len(DOCTYPES)} DocTypes, {checked} field/help/option texts, VAT=MVA')
finally:
    frappe.destroy()
